#!/usr/bin/env python3
"""Cut the frames for the hardware self test (tools/selftest) out of the raw captures in test/
and write them as C arrays to tools/selftest/replay_frames.h.

usage (from project root):  python3 test/tools/make_replay.py
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from make_vectors import ROOT, frames, load  # noqa: E402
from sml_gen import cases as synthetic_cases  # noqa: E402

OUT = os.path.join(ROOT, "tools", "selftest", "replay_frames.h")

# (meter name, capture file, max number of frames)
SOURCES = [
    ("GHWP_LGZ", "smlGHWP_261011.hex", 60),
    ("GHHS_ISK", "smlGHHS_261011.hex", 59),
    ("EMH", "EMH_eHZ-IW8E2AWL0EK2P.hex", 12),
    ("EMH_2019", "output_2019-04-27_20-39-06.hex", 2),
]


def main():
    out = [
        "// generated by test/tools/make_replay.py - do not edit",
        "#ifndef REPLAY_FRAMES_H",
        "#define REPLAY_FRAMES_H",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
    ]
    table = []
    for meter, fname, maxn in SOURCES:
        fl = list(frames(load(os.path.join(ROOT, "test", fname))))[:maxn]
        for n, fr in enumerate(fl):
            name = "R_%s_%d" % (meter, n)
            out.append("static const uint8_t %s[] = {" % name)
            for k in range(0, len(fr), 16):
                out.append("    " + ", ".join("0x%02x" % b for b in fr[k : k + 16]) + ",")
            out.append("};")
            table.append((name, meter, n))
    for name, fr, _ in synthetic_cases:  # generated variants, see sml_gen.py
        sym = "R_SYN_%s" % name
        out.append("static const uint8_t %s[] = {" % sym)
        for k in range(0, len(fr), 16):
            out.append("    " + ", ".join("0x%02x" % b for b in fr[k : k + 16]) + ",")
        out.append("};")
        table.append((sym, "SYN", name))
    out += [
        "",
        "struct ReplayFrame",
        "{",
        "    const uint8_t *data;",
        "    uint16_t len;",
        "    const char *name;",
        "};",
        "",
        "static const ReplayFrame replayFrames[] = {",
    ]
    for name, meter, n in table:
        out.append('    {%s, sizeof(%s), "%s_%s"},' % (name, name, meter, n))
    out += ["};", "static const int REPLAY_COUNT = %d;" % len(table), "", "#endif", ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(out))
    print("wrote", OUT, len(table), "frames")


if __name__ == "__main__":
    main()
