#!/usr/bin/env python3
"""Cut a handful of SML frames out of the raw captures in test/ and write them as
C arrays to test/test_decoder/sml_vectors.h (used by the regression test).

The captures are plain streams of SML frames, either binary or as hex text (whitespace and
line breaks are ignored). They carry no wall clock time, only the meter's own
sensor time inside every frame. That is why we keep a few *consecutive* frames of a
meter: they allow to check sensor time and energy delta.

usage (from project root):  python3 test/tools/make_vectors.py
"""
import binascii
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
OUT = os.path.join(ROOT, "test", "test_decoder", "sml_vectors.h")

START = b"\x1b\x1b\x1b\x1b\x01\x01\x01\x01"
END = b"\x1b\x1b\x1b\x1b\x1a"

# (symbol, capture file, indices of the frames to keep)
# GHWP: Landis+Gyr (LGZ), new meter 2026, no 16.7.0 - frame 275 is ~4.5 min after frame 0
# GHHS: Iskra (ISK), 1-0:16.7.0 available, frame 58 is ~97 s after frame 0
# EMH:  EMH eHZ (older captures, 2019 and later), 16.7.0 available
VECTORS = [
    ("GHWP_LGZ", "smlGHWP_261011.hex", [0, 1, 275]),
    ("GHHS_ISK", "smlGHHS_261011.hex", [0, 1, 58]),
    ("EMH", "EMH_eHZ-IW8E2AWL0EK2P.hex", [0, 1]),
    ("EMH_2019", "output_2019-04-27_20-39-06.hex", [0, 1]),
]


def load(path):
    d = open(path, "rb").read()
    if re.fullmatch(rb"[0-9a-fA-F\s]+", d):
        h = re.sub(rb"\s", b"", d)
        d = binascii.unhexlify(h[: len(h) & ~1])  # a cut off last nibble is possible
    return d


def frames(d):
    """complete frames (start..end flag + padding count + crc), a truncated last frame is dropped"""
    i = 0
    while True:
        s = d.find(START, i)
        if s < 0:
            return
        e = d.find(END, s + 8)
        if e < 0 or e + 8 > len(d):
            return
        yield d[s : e + 8]
        i = e + 8


def main():
    out = [
        "// generated by test/tools/make_vectors.py - do not edit",
        "#ifndef SML_VECTORS_H",
        "#define SML_VECTORS_H",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
    ]
    table = []
    for sym, fname, idx in VECTORS:
        fl = list(frames(load(os.path.join(ROOT, "test", fname))))
        for n in idx:
            if n >= len(fl):
                sys.exit("%s has only %d frames, wanted %d" % (fname, len(fl), n))
            name = "%s_%d" % (sym, n)
            fr = fl[n]
            out.append("// %s, frame %d of %d" % (fname, n, len(fl)))
            out.append("static const uint8_t %s[] = {" % name)
            for k in range(0, len(fr), 16):
                out.append("    " + ", ".join("0x%02x" % b for b in fr[k : k + 16]) + ",")
            out.append("};")
            out.append("")
            table.append((name, sym))
    out += [
        "struct SmlVector",
        "{",
        "    const char *name;",
        "    const char *meter; // which meter type",
        "    const uint8_t *data;",
        "    size_t len;",
        "};",
        "",
        "static const SmlVector smlVectors[] = {",
    ]
    for name, sym in table:
        out.append('    {"%s", "%s", %s, sizeof(%s)},' % (name, sym, name, name))
    out += ["};", "", "#endif", ""]
    open(OUT, "w").write("\n".join(out))
    print("wrote", OUT, len(table), "frames")


if __name__ == "__main__":
    main()
