// Regression test of the SML decoder (src/MeterData.h) with frames captured from real meters.
// Run on the host:  pio test -e native
//
// Important: the frames carry NO wall clock time. The only time information is the meter's own
// sensor time (actSensorTime, seconds counter) in each GetListResponse, so the tests use that.
// The expected values were read from the captures with an independent decoder (libsml dump
// and a python CRC check) and are kept here as literals.
#include <unity.h>
#include <math.h>
#include <string.h>
#include "MeterData.h"
#include "sml_vectors.h"
#include "sml_synth.h" // generated by test/tools/sml_gen.py
#include "otaversion.h"
#include "SampleAggregator.h"
#include "replay_frames.h" // all captured frames, from tools/selftest

#define BUF_SIZE_FOR_TEST 1024 // BUF_SIZE of PowerMeter.h

void setUp() {}
void tearDown() {}

static const SmlVector &vec(const char *name)
{
    for (size_t i = 0; i < sizeof(smlVectors) / sizeof(smlVectors[0]); i++)
        if (strcmp(smlVectors[i].name, name) == 0)
            return smlVectors[i];
    TEST_FAIL_MESSAGE("unknown test vector");
    return smlVectors[0];
}

static MeterDataSet decode(const char *name)
{
    MeterDataSet ds;
    const SmlVector &v = vec(name);
    TEST_ASSERT_EQUAL_MESSAGE(SML_FRAME_OK, smlDecodeFrame(v.data, v.len, ds), name);
    return ds;
}

// ---- every captured frame must decode, with a plausible content -----------------------------

void test_all_vectors_decode()
{
    for (size_t i = 0; i < sizeof(smlVectors) / sizeof(smlVectors[0]); i++)
    {
        MeterDataSet ds;
        TEST_ASSERT_EQUAL_MESSAGE(SML_FRAME_OK, smlDecodeFrame(smlVectors[i].data, smlVectors[i].len, ds),
                                  smlVectors[i].name);
        TEST_ASSERT_TRUE_MESSAGE(ds.hasSumWh, smlVectors[i].name);
        TEST_ASSERT_TRUE_MESSAGE(ds.hasSensorTime, smlVectors[i].name);
        TEST_ASSERT_TRUE_MESSAGE(strlen(ds.meterid) > 3, smlVectors[i].name);
    }
}

// ---- new Landis+Gyr meter (GHWP, 2026): other OBIS codes, no actual power ----------------------

void test_lgz_ids_and_values()
{
    MeterDataSet ds = decode("GHWP_LGZ_0");
    TEST_ASSERT_EQUAL_STRING("LGZ0a014c475a0004370688", ds.meterid);
    TEST_ASSERT_EQUAL_STRING("GHWP", ds.getalias());
    TEST_ASSERT_TRUE(ds.hasSumWh);
    TEST_ASSERT_DOUBLE_WITHIN(0.01, 478000.9, ds.sumWh); // 1-0:1.8.0, 0.1 Wh resolution
    TEST_ASSERT_TRUE(ds.hasExpWh);
    TEST_ASSERT_DOUBLE_WITHIN(0.01, 0.0, ds.expWh); // 1-0:2.8.0
    TEST_ASSERT_EQUAL_UINT32(8775977, ds.sensorTime);
}

void test_lgz_has_no_actual_power()
{
    // The meter sends no 1-0:16.7.0 (needs the PIN on the meter). The decoder must say so
    // instead of reporting 0 W.
    MeterDataSet ds = decode("GHWP_LGZ_0");
    TEST_ASSERT_FALSE(ds.hasActW);
}

